// Package lexer 把 TypeLua 源码切分成 Token 流，并附带词法诊断。
//
// 词法层是“质检分拣员”：按形状切块、贴面单，坏字符记一笔后跳过，永不停机。
// 它无状态、无回溯、无上下文：关键字是否在当前语境下是关键字，由 parser
// 决定（软关键字）。
//
// # 为什么词法永不停机
//
// 一次编译要报告所有错误；词法停在第一个坏字符会隐藏后续错误。记一笔后
// 跳过，让用户一次看到全部问题。坏字符的 Span 仍被记录，诊断能准确定位。
//
// # 扫描模型
//
// 游标式单遍扫描：src + off + line + col；peek/advance 按字节推进，Column 按
// rune 计数；长字符串/注释用 advanceBlock 批量推进。数字与字符串存原文
// （Literal），不求值。
//
// # 为什么操作符用最长匹配
//
// `...`/`..`/`.`、`//`/`/`、`>>`/`<<` 等靠最长匹配区分；唯独 `!=` 故意
// 不在词法层处理，留给 parser 把 `!` `=` 拼成 `~=`，发射时再统一——
// 词法不管、语法认账、发射归一的三段式。
//
// 明确不做
//   - 不求值字面量、不决定关键字上下文；
//   - 不做语法恢复（parser 负责）；
//   - 不保存 trivia。
//
// 不变量
//   - Lex 对任意输入都不 panic，坏输入转为诊断；
//   - Token.Span 为半开区间，Offset 单调不减；
//   - 字节偏移与行列号同时携带。
//
// 模块间协作
//   - 依赖：diag、token。
//   - 被依赖：parser（ParseFile 先 Lex）。
