// Package shake 对 TypeLua AST 做保守的 tree-shaking：删除零引用的纯局部函数。
//
// 只删 `local function f` / `local x = function` 这类纯闭包定义；其它一切
// 永远保留。安全契约的偏置是“保留”：宁可少删，绝不删错。
//
// # 为什么只动纯局部函数
//
// 全局、table/方法赋值、require/import、return、多值/属性局部、类、枚举、
// 宏、类型声明都可能有副作用或被外部引用，删错就是坏程序。只有“定义后
// 只在当前作用域内被调用、且无逃逸”的纯局部函数可安全删除，且做可达性
// 传递闭包。
//
// # 为什么 fail-safe
//
// 任何无法识别的语句/表达式节点都会污染运行，最终什么都不删。这样未来
// 新增语言构造时，行为退化为“不删”，而不是误删。
//
// 明确不做
//   - 不做跨文件/全局的死代码消除；
//   - 不删除有副作用或可能逃逸的定义；
//   - 不改变语义，只删除语句。
//
// 不变量
//   - ShakeFile 只删除死的纯局部函数定义语句；
//   - 识别失败时删除数量为 0；
//   - 作用域与遮蔽按 Lua 语义处理，类型/字段名空间不计数。
//
// 模块间协作
//   - 依赖：ast。
//   - 被依赖：emitter（可选 TreeShake 在并发检测前运行）。
