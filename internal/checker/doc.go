// Package checker 实现 TypeLua 的类型检查器：作用域、符号表、类型推断与窄化。
//
// 检查器是“监理”：只贴整改单（如 `local x: string = 123` 报 TL32xx），绝不动图纸（AST）。
// 它登记名字、翻译类型、逐式校验，遇错填 `any` 续查（如坏实参后仍查下一句），类型全住符号表。
//
// # 为什么检查器不改 AST
//
// AST 是前后工序唯一的事实来源；如果检查器改写 AST，发射器就必须理解
// 检查器的改写，类型擦除的结构性保证就破了。把类型信息放在符号表里，
// 发射器完全看不到类型，也就改不坏语义。这也是“遇错填 any 继续”的物理
// 基础：AST 形状不变，后续节点仍可按原形状检查。
//
// # 核心数据
//
//   - Scope：父子链的作用域，vars/types 两本名册分家，支持遮蔽与向上查找；
//   - Symbol：值侧名字的类型与属性；
//   - typeEntry：类型侧声明的身份、泛型参数、缓存与递归守卫；
//   - Checker：遍历状态机（作用域栈、返回栈、标签/跳转、类型参数栈、类上下文）。
//
// # 为什么 vars 与 types 分表
//
// `local Foo = 1` 与 `type Foo = string` 同名共存（如类 `Dog` 同时占值册与类型册），
// 分表让 `d.name` 查值、`Dog` 查类型互不串味；排查遮蔽先看查的是哪本册。
//
// # 递归与缓存
//
// typeEntry 用 resolving 守卫递归定义，用 cached/cacheInst 缓存非泛型与
// 泛型实例；类用 shell 对象支持递归引用。子类型判定的 seen 集、替换的
// 记忆表、类的 shell 是同一思想的三次登场：先占位、后填充、防循环。
//
// # 窄化
//
// `if x ~= nil` 在真分支里把 x 临时看作更窄的类型，通过作用域内符号的
// 阴影副本实现，SameAs 把阴影链回原定义，保证引用/重命名仍指向声明。
//
// 明确不做
//   - 不改写 AST、不生成代码；
//   - 不做跨文件的全局符号合并（由 compiler 按依赖顺序喂 RequireTypes/Ambient）；
//   - 不做并发安全的符号表（单文件单检查器）。
//
// 不变量
//   - AST 在检查过程中保持不变（除宏展开这一显式前置步骤）；
//   - 类型信息只存在于符号表/typeEntry，不回写 AST；
//   - 遇错填 `any`，后续节点继续检查，诊断不中断；
//   - retDepth 守卫保证 super 改写只在方法入口层生效。
//
// 模块间协作
//   - 依赖：ast、diag、expand（宏展开）、token、types。
//   - 被依赖：compiler（CheckFile/CheckFileIndexed）、lsp（符号索引/导航）。
