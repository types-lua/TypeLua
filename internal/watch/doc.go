// Package watch 实现 tsc 风格的 --watch 轮询重建。
//
// 监视集合由 config 的文件列表加上配置文件本身导出，因此只在构建输入集
// 变化时触发重建；输出目录永远不被监视，避免发射触发再重建的自循环。
// 使用轮询（无外部依赖，全平台可用）+ 防抖合并：快速保存折叠为一次重建，
// 每次重建后刷新基线，构建中途的编辑不丢失。
//
// # 为什么是轮询而非 inotify
//
// inotify/FSEvents 在不同平台与容器里行为不一致，且监听句柄管理复杂；
// 轮询虽然有延迟，但行为可预测、无依赖、全平台一致，对编译器工具来说
// 正确性与可移植性优先于实时性。
//
// # 为什么输出目录不监视
//
// 发射会写输出目录；若监视它，每次构建都会触发下一次构建，形成自循环。
// 把“输入集”与“输出集”从定义上分开，从源头断掉循环。
//
// 明确不做
//   - 不做文件内容 diff（只比对元信息/哈希）；
//   - 不做增量编译（整库重建）；
//   - 不做跨进程协调。
//
// 不变量
//   - 监视集合 ⊆ 构建输入集 ∪ 配置文件；
//   - 输出目录永远不在监视集合中；
//   - 防抖窗口内多次变化折叠为一次重建。
//
// 模块间协作
//   - 依赖：config、compiler。
//   - 被依赖：cmd/tlua（watch 子命令）。
