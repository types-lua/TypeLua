// Package toml 实现 tlua 清单与锁文件使用的严格 TOML 子集。
//
// 它提供确定性的编码与解码，支持表、数组表、键值、字符串、整数、浮点、
// 布尔、数组与单行内联表；不支持的构造（日期时间、进制整数、多行字符串）
// 给出明确错误。解码只保留值，编码顺序由调用方决定。
//
// # 为什么自实现而非引库
//
// 清单与锁文件是项目输入，格式必须可控、错误信息必须可读、输出必须确定性。
// 引入通用 TOML 库会把不支持的特性带进来，且错误信息与编码顺序不可控。
// 严格子集让“不支持”变成显式错误，而不是静默接受。
//
// 明确不做
//   - 不支持完整 TOML 规范（日期时间、进制整数、多行字符串）；
//   - 不做 schema 校验（mod 包负责）；
//   - 不做并发安全（调用方串行化）。
//
// 不变量
//   - 解码失败返回明确错误，不 panic；
//   - 编码输出确定性（相同输入相同字节）；
//   - 不支持的构造一律报错，不静默忽略。
//
// 模块间协作
//   - 依赖：无内部包（仅标准库）。
//   - 被依赖：mod（manifest/lock）。
package toml
