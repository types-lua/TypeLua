// Package expand 实现 TypeLua 的卫生宏（hygienic macros）：复印、改名、代入。
//
// 宏在类型检查之前展开并擦除定义，因此检查器与发射器完全不知道宏存在。
// 展开是幂等的：第二次运行找不到定义，什么都不改。
//
// # 为什么宏必须在检查之前展开
//
// 宏是编译期语法改写；若在检查之后展开，类型信息与 AST 形状会脱节。
// 先展开、再检查，保证检查器看到的是最终代码形状，与手写等价。
//
// # 为什么需要卫生（改名）
//
// 宏体里引用的名字可能与调用点作用域冲突；展开时为捕获的名字生成唯一
// 新名（fresh），避免宏内部绑定泄漏到调用点，也避免调用点名字被宏意外
// 捕获。这是“复印、改名、代入”三步里“改名”的全部意义。
//
// # 展开策略
//
//   - 先收集当前块的所有宏定义（支持前向引用），再展开语句与表达式；
//   - 递归深度上限防止无限展开；
//   - 表达式宏与语句宏分别处理；尾随 `...` 收集多余实参，仅在调用实参
//     位置可 splice。
//
// 明确不做
//   - 不做类型感知的展开（宏只看语法）；
//   - 不支持宏的条件编译/递归宏 beyond 深度上限；
//   - 不保留宏定义到发射阶段（定义被擦除）。
//
// 不变量
//   - ExpandFile 幂等；
//   - 展开后的 AST 仍满足 ast 的家族契约；
//   - 深度超限报告诊断而非 panic。
//
// 模块间协作
//   - 依赖：ast、diag、token。
//   - 被依赖：checker（检查前调用 ExpandFile）。
