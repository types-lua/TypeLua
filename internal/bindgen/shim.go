package bindgen

// 类型化 shim 生成：单一真相来源的第二半。
//
// `Generate` 产生 .d.tl 契约；`GenerateShim` 从同一头文件产生 .tl
// 加载器（require ffi + cdef + load + 单个 `as` + return），因此编辑 .h
// 并重跑一次 bindgen 命令即可保持三件产物（头文件、契约、shim）同步。
// 调用方只需 `import C from "mylib"`，零转换。
//
// 与 Generate 一样总而全：任何头文件都产生可解析的 shim。嵌入的
// cdef 块是剥离守卫后的源（注释 + `#` 行移除）；
// `#ifdef` 变体由作者在 ffi.cdef 运行时负责。

import (
	"fmt"
	"path/filepath"
	"strings"
)

// DefaultSoName 从头文件路径推导同级共享库名：
// mylib.h -> libmylib.so（已有 lib* 前缀保留：libfoo.h -> libfoo.so）。
//
// 设计者视角：去扩展（.h/.hpp/.hxx/.hh 大小写不敏感）+ `lib` 前缀归一+`.so`。
// 障碍是 `LIBFoo.H` 大小写：低判。候选：推导 vs 必传；选推导可覆。排查现场：
// 库名错先查扩展剥离。
func DefaultSoName(headerPath string) string {
	base := filepath.Base(headerPath)
	for _, ext := range []string{".hpp", ".hxx", ".hh", ".h"} {
		if strings.HasSuffix(strings.ToLower(base), ext) {
			base = base[:len(base)-len(ext)]
			break
		}
	}
	if strings.HasPrefix(base, "lib") {
		return base + ".so"
	}
	return "lib" + base + ".so"
}

// CdefBody 返回头文件的 ffi.cdef 载荷：注释与预处理行剥离，
// 边缘空行修剪。从不失败；空输入产生空（仍有效）体。
//
// 设计者视角：stripComments 去注+`#` 行，Trim 去边，空亦有效（cdef 空块）。
// 障碍是 `#ifdef` 变体：留运行时（见包注）。排查现场：cdef 错先查剥离。
func CdefBody(headerSrc string) string {
	return strings.Trim(stripComments(headerSrc), "\n")
}

// longString 把 body 包成 Lua 长字符串；当 body 自身含闭合括号时
// 升一级（C 中几乎不会，但生成必须总而全）。
//
// 设计者视角：含 `]]` 即升 `[=[ ]=]`，保任何体可嵌。障碍是体含 `]=]`：仍罕见，
// 两级够。排查现场：shim 语法错先查闭合。
func longString(body string) string {
	if !strings.Contains(body, "]]") {
		return "[[\n" + body + "\n]]"
	}
	return "[=[\n" + body + "\n]=]"
}

// GenerateShim 渲染类型化 .tl 加载器。headerName 仅用于显示
// （如 "mylib.h"，用于重新生成注释）；libName 是 ambient 契约接口
// （如 "CMyLib"）；soName 是同级库文件（如 "libmylib.so"，见 DefaultSoName）。
// 空 libName 默认 CLib；空 soName 从 headerName 推导。
//
// 设计者视角：shim 三件——`require ffi`+cdef 长串+`libDir()` 自定位+
// `ffi.load(dir..so) as Lib` 单 `as` 收口。障碍是 source/dist 双布局：libDir 经
// debug.getinfo 自定位，同级 so 永对。候选：LUA_PATH vs 自定位；选自定位零配。
// 不变量：空参全兜底。排查现场：so 找不到先查 libDir，类型不对先查 `as`。
func GenerateShim(headerSrc, headerName, libName, soName string) string {
	if strings.TrimSpace(libName) == "" {
		libName = "CLib"
	}
	if strings.TrimSpace(headerName) == "" {
		headerName = "mylib.h"
	}
	if strings.TrimSpace(soName) == "" {
		soName = DefaultSoName(headerName)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- Generated by `tlua bindgen --header %s --shim <out.tl> --lib %s`; do not edit.\n", headerName, libName)
	fmt.Fprintf(&b, "-- Source of truth: %s. Regenerate after editing the header.\n", headerName)
	fmt.Fprintf(&b, "-- Callers just `import C from \"mylib\"` — the single `as` lives here.\n")
	fmt.Fprintf(&b, "-- Runtime: LuaJIT + %s beside this file (sh build.sh).\n\n", soName)
	b.WriteString("local ffi = require(\"ffi\")\n\n")
	fmt.Fprintf(&b, "ffi.cdef%s\n\n", longString(CdefBody(headerSrc)))
	b.WriteString("-- .so sits beside this file in both source and dist layouts.\n")
	b.WriteString("local function libDir(): string\n")
	b.WriteString("  local info = debug.getinfo(1, \"S\")\n")
	b.WriteString("  local src = info.source\n")
	b.WriteString("  if string.sub(src, 1, 1) == \"@\" then\n")
	b.WriteString("    src = string.sub(src, 2)\n")
	b.WriteString("  end\n")
	b.WriteString("  local dir = string.match(src, \"^(.*/)\")\n")
	b.WriteString("  if dir == nil then\n")
	b.WriteString("    return \"./\"\n")
	b.WriteString("  end\n")
	b.WriteString("  return dir\n")
	b.WriteString("end\n\n")
	fmt.Fprintf(&b, "local M = ffi.load(libDir() .. \"%s\") as %s\n", soName, libName)
	b.WriteString("return M\n")
	return b.String()
}
