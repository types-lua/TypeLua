package bindgen

// C header subset -> TypeLua .d.tl (cross-language type contract).
//
// Total and defensive: unknown constructs never error, they become `any`
// with a `-- skipped` comment, so output always parses. Supported:
//
//	typedef struct { ... } Name;  struct Name { ... };
//	typedef enum { A, B = 5 } Name;  enum Name { ... };
//	typedef <type> Alias;  (scalar -> mapped, else any/cdata)
//	<ret> <name>(<params>);  (prototypes -> interface methods)
//	#define NAME <int|string>  (-> interface readonly field)
//	function pointers: typedef R (*Cb)(P...) -> type Cb = (…)->R
//
// Mapping (C -> TypeLua): integers -> integer, float/double -> number,
// char*/const char* -> string, other * / arrays -> cdata, void -> void,
// bool -> boolean, known struct/enum names stay nominal, unknown by-value
// custom types -> any (permissive, no false positives like stdlib shims).

import (
	"fmt"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var identRe = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// Generate renders a .d.tl contract for headerSrc. libName is the interface
// holding functions + #defines (default CLib).
func Generate(headerSrc, libName string) string {
	if strings.TrimSpace(libName) == "" {
		libName = "CLib"
	}
	p := &parser{known: map[string]bool{}}
	p.scanDefines(headerSrc)
	src := stripComments(headerSrc)
	decls := splitTopLevel(src)
	for _, d := range decls {
		p.handleDecl(strings.TrimSpace(d))
	}
	var b strings.Builder
	fmt.Fprintf(&b, "-- Generated by `tlua bindgen`; do not edit.\n")
	fmt.Fprintf(&b, "-- Source header subset -> TypeLua contract (C ABI via ffi).\n")
	fmt.Fprintf(&b, "-- Pointers/arrays are `cdata` (except char* -> string);\n")
	fmt.Fprintf(&b, "-- unknown by-value types are `any` (no false positives).\n")
	fmt.Fprintf(&b, "-- Usage: local C = ffi.load(\"mylib\") as %s\n\n", libName)
	// Deterministic: structs, enums, aliases sorted; methods in source order.
	names := append([]string(nil), p.structOrder...)
	sort.Strings(names)
	for _, n := range names {
		b.WriteString(p.structs[n])
		b.WriteString("\n")
	}
	enames := append([]string(nil), p.enumOrder...)
	sort.Strings(enames)
	for _, n := range enames {
		b.WriteString(p.enums[n])
		b.WriteString("\n")
	}
	anames := append([]string(nil), p.aliasOrder...)
	sort.Strings(anames)
	for _, n := range anames {
		b.WriteString(p.aliases[n])
		b.WriteString("\n")
	}
	if len(p.methods) > 0 || len(p.defines) > 0 {
		fmt.Fprintf(&b, "interface %s {\n", libName)
		for _, d := range p.defines {
			fmt.Fprintf(&b, "  %s,\n", d)
		}
		for _, m := range p.methods {
			fmt.Fprintf(&b, "  %s,\n", m)
		}
		b.WriteString("}\n")
	} else {
		fmt.Fprintf(&b, "-- (no functions/defines found)\n")
	}
	for _, s := range p.skipped {
		fmt.Fprintf(&b, "-- skipped: %s\n", s)
	}
	return b.String()
}

type parser struct {
	known       map[string]bool
	structs     map[string]string
	structOrder []string
	enums       map[string]string
	enumOrder   []string
	aliases     map[string]string
	aliasOrder  []string
	methods     []string
	defines     []string
	skipped     []string
}

func (p *parser) addStruct(name, body string) {
	if p.structs == nil {
		p.structs = map[string]string{}
	}
	if _, ok := p.structs[name]; ok {
		return
	}
	p.known[name] = true
	p.structs[name] = body
	p.structOrder = append(p.structOrder, name)
}

func (p *parser) addEnum(name, body string) {
	if p.enums == nil {
		p.enums = map[string]string{}
	}
	if _, ok := p.enums[name]; ok {
		return
	}
	p.known[name] = true
	p.enums[name] = body
	p.enumOrder = append(p.enumOrder, name)
}

func (p *parser) addAlias(name, body string) {
	if p.aliases == nil {
		p.aliases = map[string]string{}
	}
	if _, ok := p.aliases[name]; ok {
		return
	}
	p.known[name] = true
	p.aliases[name] = body
	p.aliasOrder = append(p.aliasOrder, name)
}

// scanDefines collects simple #defines before comment stripping (so values
// with // inside strings survive; we only accept int/string literals).
func (p *parser) scanDefines(src string) {
	for _, line := range strings.Split(src, "\n") {
		t := strings.TrimSpace(line)
		if !strings.HasPrefix(t, "#define") {
			continue
		}
		rest := strings.TrimSpace(strings.TrimPrefix(t, "#define"))
		fields := strings.Fields(rest)
		if len(fields) != 2 || !identRe.MatchString(fields[0]) {
			continue
		}
		name, val := fields[0], strings.TrimSpace(fields[1])
		if isIntLit(val) {
			p.defines = append(p.defines, fmt.Sprintf("%s: %s", name, val))
		} else if isStringLit(val) {
			p.defines = append(p.defines, fmt.Sprintf("%s: %s", name, val))
		}
	}
}

func isIntLit(s string) bool {
	s = strings.TrimSpace(s)
	if s == "" {
		return false
	}
	neg := false
	if strings.HasPrefix(s, "-") || strings.HasPrefix(s, "+") {
		neg = s[0] == '-'
		_ = neg
		s = strings.TrimSpace(s[1:])
	}
	if strings.HasPrefix(s, "0x") || strings.HasPrefix(s, "0X") {
		_, err := strconv.ParseInt(s, 0, 64)
		return err == nil
	}
	_, err := strconv.ParseInt(s, 10, 64)
	return err == nil
}

func isStringLit(s string) bool {
	s = strings.TrimSpace(s)
	return len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"'
}

func stripComments(src string) string {
	var b strings.Builder
	i := 0
	for i < len(src) {
		if i+1 < len(src) && src[i] == '/' && src[i+1] == '/' {
			for i < len(src) && src[i] != '\n' {
				i++
			}
			continue
		}
		if i+1 < len(src) && src[i] == '/' && src[i+1] == '*' {
			i += 2
			for i+1 < len(src) && !(src[i] == '*' && src[i+1] == '/') {
				if src[i] == '\n' {
					b.WriteByte('\n')
				}
				i++
			}
			i += 2
			if i > len(src) {
				i = len(src)
			}
			continue
		}
		b.WriteByte(src[i])
		i++
	}
	// Drop preprocessor lines (defines already scanned).
	var out strings.Builder
	for _, line := range strings.Split(b.String(), "\n") {
		if strings.HasPrefix(strings.TrimSpace(line), "#") {
			continue
		}
		out.WriteString(line)
		out.WriteByte('\n')
	}
	return out.String()
}

// splitTopLevel splits on ';' at brace/paren depth 0.
func splitTopLevel(src string) []string {
	var out []string
	depthBrace, depthParen := 0, 0
	start := 0
	for i := 0; i < len(src); i++ {
		switch src[i] {
		case '{':
			depthBrace++
		case '}':
			if depthBrace > 0 {
				depthBrace--
			}
		case '(':
			depthParen++
		case ')':
			if depthParen > 0 {
				depthParen--
			}
		case ';':
			if depthBrace == 0 && depthParen == 0 {
				out = append(out, src[start:i])
				start = i + 1
			}
		}
	}
	return out
}

func (p *parser) handleDecl(d string) {
	if d == "" {
		return
	}
	t := strings.TrimSpace(d)
	if t == "" {
		return
	}
	// Function pointer typedef: typedef R (*Name)(P...);
	// parseFuncPtrTypedef already returns a full `type X = ...` body.
	if strings.HasPrefix(t, "typedef") && strings.Contains(t, "(*") {
		if name, ft := parseFuncPtrTypedef(t, p.known); name != "" {
			p.addAlias(name, ft)
			return
		}
		p.skipped = append(p.skipped, oneLine(t))
		return
	}
	if strings.HasPrefix(t, "typedef") {
		p.handleTypedef(strings.TrimSpace(strings.TrimPrefix(t, "typedef")))
		return
	}
	if strings.HasPrefix(t, "struct") && strings.Contains(t, "{") {
		if name, body := parseStructDecl(t, false, p.known); name != "" {
			p.addStruct(name, body)
			return
		}
		p.skipped = append(p.skipped, oneLine(t))
		return
	}
	if strings.HasPrefix(t, "enum") && strings.Contains(t, "{") {
		if name, body := parseEnumDecl(t); name != "" {
			p.addEnum(name, body)
			return
		}
		p.skipped = append(p.skipped, oneLine(t))
		return
	}
	if strings.HasPrefix(t, "struct") || strings.HasPrefix(t, "enum") || strings.HasPrefix(t, "union") {
		// Forward decl (`struct Foo;`) carries no fields; skip silently
		// unless it names something (map to cdata alias for nominal use).
		if name := forwardDeclName(t); name != "" && !p.known[name] {
			p.addAlias(name, fmt.Sprintf("type %s = cdata", name))
			return
		}
		return
	}
	// Prototype: must contain '(' and look like `ret name(params)`.
	if strings.Contains(t, "(") && strings.Contains(t, ")") && !strings.Contains(t, "{") {
		if m := parsePrototype(t, p.known); m != "" {
			p.methods = append(p.methods, m)
			return
		}
		p.skipped = append(p.skipped, oneLine(t))
		return
	}
	// Top-level variable? `extern int x;` -> skip (belongs in interface only
	// via explicit header review); record to avoid silent loss.
	if t != "" {
		p.skipped = append(p.skipped, oneLine(t))
	}
}

func (p *parser) handleTypedef(t string) {
	t = strings.TrimSpace(t)
	if t == "" {
		return
	}
	// typedef struct/enum {...} Name;
	if strings.Contains(t, "{") {
		if strings.Contains(t, "struct") {
			if name, body := parseStructDecl("typedef "+t, true, p.known); name != "" {
				p.addStruct(name, body)
				return
			}
		}
		if strings.Contains(t, "enum") {
			inner := t
			// typedef enum {...} Name -> enum Name {...}
			if name, body := parseEnumDecl("enum " + afterBraceTypedefName(t, inner)); name != "" {
				_ = body
				// parseEnumDecl expects full decl; reconstruct:
				if n2, b2 := parseEnumDecl("enum " + typedefTrailingName(t) + " " + bracePart(t)); n2 != "" {
					p.addEnum(n2, b2)
					return
				}
			}
		}
		p.skipped = append(p.skipped, oneLine("typedef "+t))
		return
	}
	// typedef <type> Name; (single declarator only; multi-declarator skipped)
	if strings.Contains(t, ",") {
		p.skipped = append(p.skipped, oneLine("typedef "+t))
		return
	}
	// Split trailing name: last ident is the alias.
	fields := strings.Fields(t)
	if len(fields) < 2 {
		p.skipped = append(p.skipped, oneLine("typedef "+t))
		return
	}
	alias := cleanIdent(fields[len(fields)-1])
	if !identRe.MatchString(alias) {
		p.skipped = append(p.skipped, oneLine("typedef "+t))
		return
	}
	base := strings.TrimSpace(strings.TrimSuffix(t, fields[len(fields)-1]))
	base = strings.TrimSpace(strings.TrimSuffix(base, "*") + starSuffix(fields[len(fields)-1]))
	mapped := mapCType(base, p.known)
	// Pointers already map to cdata/string; by-value unknowns stay any.
	p.addAlias(alias, fmt.Sprintf("type %s = %s", alias, mapped))
}

func starSuffix(last string) string {
	if strings.Contains(last, "*") {
		return " *"
	}
	return ""
}

func oneLine(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	if len(s) > 120 {
		return s[:120] + "..."
	}
	return s
}
